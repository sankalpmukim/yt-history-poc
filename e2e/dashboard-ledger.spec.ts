import { test, expect } from "./fixtures"

test("Ledger search, subcategory filter, bulk assign/clear, and single-row subcategory label", async ({ ledger }) => {
  const { page, seed } = ledger
  await seed()
  await page.getByRole("link", { name: /Ledger/ }).click()
  await expect(page.getByRole("heading", { name: "Ledger" })).toBeVisible()

  const search = page.getByPlaceholder("Search title or channel…")
  await search.fill("airline fleet")
  const matchingRow = page.getByRole("row").filter({ hasText: "airline fleet news" })
  await expect(matchingRow).toHaveCount(1)

  await search.clear()
  await page.locator("select").selectOption("news-world")
  const filteredRows = page.locator("table.ledger tbody tr")
  await expect(filteredRows).toHaveCount(2)
  await expect(filteredRows.first()).toContainText("News & updates › World news")

  await page.locator("select").selectOption("all")
  await search.fill("airline fleet")
  const row = page.getByRole("row").filter({ hasText: "airline fleet news" })
  await row.locator('input[type="checkbox"]').check()
  await page.getByRole("button", { name: "Choose category…" }).click()
  await page.getByRole("combobox", { name: "Search categories and subcategories" }).fill("Coding")
  await page.getByRole("option", { name: "⌨️ Practical how-tos › Coding" }).click()
  await page.getByRole("button", { name: "Apply", exact: true }).click()
  await expect(row).toContainText("Practical how-tos › Coding")

  await row.locator('input[type="checkbox"]').check()
  await page.getByRole("button", { name: "Clear overrides" }).click()
  await expect(row).toContainText("News & updates › World news")

  await search.fill("aircraft industry")
  const singleRow = page.getByRole("row").filter({ hasText: "aircraft industry update" })
  await singleRow.locator("button.chip").click()
  await page.getByRole("combobox", { name: "Search categories and subcategories" }).fill("Coding")
  await page.getByRole("option", { name: "⌨️ Practical how-tos › Coding" }).click()
  await page.getByRole("button", { name: "Apply", exact: true }).click()
  await expect(singleRow).toContainText("Practical how-tos › Coding")

  await singleRow.locator("button.chip").click()
  const pickerSearch = page.getByRole("combobox", { name: "Search categories and subcategories" })
  await expect(page.getByRole("button", { name: /Create category/ })).toHaveCount(0)
  await pickerSearch.fill("Field Notes")
  await expect(page.getByRole("button", { name: 'Create category “Field Notes”' })).toBeEnabled()
  await page.getByRole("button", { name: 'Create category “Field Notes”' }).click()
  await page.getByRole("button", { name: "Apply", exact: true }).click()
  await expect(singleRow).toContainText("Field Notes")

  await singleRow.locator("button.chip").click()
  await pickerSearch.fill("Field Notes")
  const duplicateCategory = page.getByRole("button", { name: 'Create category “Field Notes”' })
  await expect(duplicateCategory).toBeDisabled()
  await expect(page.getByText("That category already exists.")).toBeVisible()
  await page.getByRole("button", { name: "Edit Field Notes" }).click()
  await page.getByLabel("Name").clear()
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("alert").filter({ hasText: "Name cannot be empty." })).toBeVisible()
  await page.getByLabel("Name").fill("News & updates")
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await expect(page.getByRole("alert").filter({ hasText: "That name is already used in this list." })).toBeVisible()
  await page.getByLabel("Name").fill("Flight Journal")
  await page.getByLabel("Emoji").fill("✈️")
  await page.getByLabel("Color").fill("#0f766e")
  await page.getByRole("button", { name: "Save", exact: true }).click()
  await pickerSearch.fill("Dispatch")
  await page.getByRole("button", { name: 'Create “Dispatch” under Flight Journal' }).click()
  await page.getByRole("button", { name: "Apply", exact: true }).click()
  await expect(singleRow).toContainText("Flight Journal › Dispatch")
  await singleRow.locator("button.chip").click()
  await pickerSearch.fill("Dispatch")
  await expect(page.getByRole("button", { name: 'Create “Dispatch” under Flight Journal' })).toBeDisabled()
  await expect(page.getByText("That subcategory already exists.")).toBeVisible()
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
})
